#!/usr/bin/env node
// Builds the Nucleo icon set, for those who own a Nucleo license: exports the
// icons that src/icon/nucleo.json names from the Nucleo desktop app's library
// into src/icon/svg/, then generates src/icon/nucleo.generated.tsx with the
// same names as src/icon/lucide.tsx. Both outputs stay out of Git: Nucleo's
// artwork may not be redistributed.
//
//   pnpm --filter @opai/ui icons          export what is missing, then build
//   pnpm --filter @opai/ui icons build    build from src/icon/svg/ only
//
// Exporting reads the library (Nucleo UI family, outline, 18px grid), so the
// app must be installed and signed in on this machine.
import { execFileSync } from "node:child_process";
import { mkdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { homedir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const packageRoot = join(dirname(fileURLToPath(import.meta.url)), "..");
const iconDir = join(packageRoot, "src/icon");
const svgDir = join(iconDir, "svg");
const generatedFile = join(iconDir, "nucleo.generated.tsx");
const library =
  process.env.NUCLEO_LIBRARY ?? join(homedir(), "Library/Application Support/Nucleo/icons");

const FAMILY = "Nucleo UI";
const GRID = 18;
const STYLE = "outline";

/** Semantic name → Nucleo icon name. */
const names = JSON.parse(readFileSync(join(iconDir, "nucleo.json"), "utf8"));
const lucide = [
  ...readFileSync(join(iconDir, "lucide.tsx"), "utf8").matchAll(/^export const (\w+) =/gm),
].map((match) => match[1]);
const missing = lucide.filter((name) => !(name in names));
const extra = Object.keys(names).filter((name) => !lucide.includes(name));
if (missing.length > 0 || extra.length > 0) {
  console.error(
    `nucleo.json and lucide.tsx must name the same icons. Missing in nucleo.json: ${missing.join(", ") || "none"}. Not in lucide.tsx: ${extra.join(", ") || "none"}.`,
  );
  process.exit(1);
}

const [command] = process.argv.slice(2);
if (command === undefined) {
  const wanted = [...new Set(Object.values(names))].filter(
    (name) => !existsSync(join(svgDir, `${name}.svg`)),
  );
  if (wanted.length > 0) await add(wanted);
  build();
} else if (command === "build") {
  build();
} else {
  console.error("Usage: nucleo-icons.mjs [build]");
  process.exit(1);
}

async function add(iconNames) {
  const { DatabaseSync } = await import("node:sqlite");
  const databasePath = join(library, "data.sqlite3");
  if (!existsSync(databasePath)) {
    throw new Error(`No Nucleo library at ${library}. Install and open the Nucleo app first.`);
  }
  const database = new DatabaseSync(databasePath, { readOnly: true });
  const query = database.prepare(
    `select icons.id, icons.set_id from icons
       join sets on sets.id = icons.set_id
       join groups on groups.id = sets.group_id
     where groups.title = ? and icons.grid = ? and icons.klass = ? and icons.name = ?
     order by icons.id limit 1`,
  );

  mkdirSync(svgDir, { recursive: true });
  for (const name of iconNames) {
    const row = query.get(FAMILY, GRID, STYLE, name);
    if (!row) throw new Error(`No "${name}" in ${FAMILY}, ${STYLE}, ${GRID}px.`);
    const source = readFileSync(join(library, "sets", String(row.set_id), `${row.id}.svg`), "utf8");
    writeFileSync(join(svgDir, `${name}.svg`), `${normalize(source)}\n`);
    console.log(`Exported ${name}.svg`);
  }
}

/** Paints with currentColor and drops the app's wrapper class. */
function normalize(svg) {
  return svg
    .replace(/\s+class="nc-icon-wrapper"/g, "")
    .replace(/(stroke|fill)="(#000|#000000|black)"/g, '$1="currentColor"')
    .replace(/>\s+</g, "><")
    .trim();
}

function build() {
  const components = Object.entries(names)
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([semantic, name]) => {
      const file = join(svgDir, `${name}.svg`);
      if (!existsSync(file)) throw new Error(`No ${name}.svg: run the command without "build".`);
      const svg = readFileSync(file, "utf8");
      const viewBox = /viewBox="([^"]+)"/.exec(svg)?.[1] ?? `0 0 ${GRID} ${GRID}`;
      const inner = /<svg[^>]*>([\s\S]*)<\/svg>/.exec(svg)?.[1] ?? "";
      return [
        `/** Nucleo UI, ${STYLE}, ${GRID}px: ${name} */`,
        `export function ${semantic}(props: IconProps) {`,
        `  return (`,
        `    <svg xmlns="http://www.w3.org/2000/svg" viewBox="${viewBox}" width="1em" height="1em" {...props}>`,
        `      ${toJsx(inner)}`,
        `    </svg>`,
        `  );`,
        `}`,
      ].join("\n");
    });

  writeFileSync(
    generatedFile,
    [
      "// Generated by packages/ui/scripts/nucleo-icons.mjs from src/icon/svg/. Do not edit.",
      'import type { IconProps } from "./props";',
      "",
      components.join("\n\n"),
      "",
    ].join("\n"),
  );
  // Same layout as `pnpm format`, so a rebuild leaves no diff.
  const oxfmt = join(packageRoot, "../../node_modules/.bin/oxfmt");
  if (existsSync(oxfmt)) execFileSync(oxfmt, [generatedFile], { stdio: "ignore" });
  console.log(`Generated ${components.length} icons.`);
}

/** SVG attributes to JSX: stroke-width becomes strokeWidth, data-* and aria-* stay. */
function toJsx(markup) {
  return markup
    .replace(/\s([a-z]+(?:-[a-z]+)+)=/g, (match, attribute) =>
      /^(data|aria)-/.test(attribute)
        ? match
        : ` ${attribute.replace(/-([a-z])/g, (_, letter) => letter.toUpperCase())}=`,
    )
    .replace(/\sclass=/g, " className=");
}
